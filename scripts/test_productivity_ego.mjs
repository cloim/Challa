await page.press('loc=css:input[aria-label="빠른 스니펫 검색"]','Enter');
await page.waitForSelector('loc=css:input[aria-label="빈칸 고객명"]');
await page.fill('loc=css:input[aria-label="빈칸 고객명"]','검증 사용자');
await page.click('loc=css:button[type="submit"]');
await page.waitForFunction(()=>window.productivityFixture.submissions.length===1);
let submitted=await page.evaluate(()=>window.productivityFixture.submissions[0]);
if(submitted.snippetId!=='template'||submitted.values['고객명']!=='검증 사용자'||!submitted.values['날짜'])throw Error('template submission');
await page.evaluate(()=>window.productivityFixture.open());
await page.waitForFunction(()=>document.body.textContent.includes('example.exe | 업무 프로필'));
await page.fill('loc=css:input[aria-label="빠른 스니펫 검색"]',':plain');
await page.press('loc=css:input[aria-label="빠른 스니펫 검색"]','Enter');
await page.waitForFunction(()=>window.productivityFixture.submissions.length===2);
await page.evaluate(()=>window.productivityFixture.open());
await page.waitForFunction(()=>document.body.textContent.includes('example.exe | 업무 프로필'));
await page.fill('loc=css:input[aria-label="빠른 스니펫 검색"]',':account');
await page.press('loc=css:input[aria-label="빠른 스니펫 검색"]','Enter');
await page.waitForFunction(()=>document.querySelector('[role="alert"]')?.textContent.includes('보관함 잠김'));
if(await page.evaluate(()=>window.productivityFixture.submissions.length)!==2)throw Error('locked vault submitted');
console.log({quickSearchAndEnter:'passed',templateSubmission:'passed',lockedVault:'passed'});
await page.goto('http://127.0.0.1:4180/?fixture=main#/snippets');
await page.waitForSelector('loc=css:button[aria-label="일반 문구: 사용 가능"]');
await page.evaluate(()=>{const f=window.productivityFixture;f.engine.paused=true;f.product.readiness.plain='paused';f.emit('engine-state',structuredClone(f.engine));f.emit('productivity-state',structuredClone(f.product));});
await page.waitForSelector('loc=css:button[aria-label="일반 문구: 엔진 일시 정지"]');
await page.evaluate(()=>{window.productivityFixture.checkStarted=performance.now();window.productivityFixture.engineCalls=window.productivityFixture.calls.filter(c=>c==='get_engine_status').length;});
await page.waitForFunction(()=>performance.now()-window.productivityFixture.checkStarted>6000);
const poll=await page.evaluate(()=>{const f=window.productivityFixture;return f.calls.filter(c=>c==='get_engine_status').length-f.engineCalls;});
if(poll!==0)throw Error('unexpected UI status polling');
const results={quickSearchAndEnter:true,templateSubmission:true,lockedVault:true,stateEvents:true,uiPollingCalls:poll};
await fs.mkdir(new URL('../docs/',import.meta.url),{recursive:true});await fs.writeFile(new URL('../docs/productivity-ipc-results.json',import.meta.url),JSON.stringify(results,null,2));
console.log(results);console.log(await page.snapshot());
if (ownSpace) await task.finish({keep:[]});
