const ownSpace = globalThis.challaTestSpace === undefined;
const task=await taskSpace(globalThis.challaTestSpace ?? `Challa 기능 검증 ${new Date().toISOString()}`);
const page=task.page(globalThis.challaTestPage ?? 'p1');
await page.cdp('Page.addScriptToEvaluateOnNewDocument',{source:await fs.readFile(new URL('./fixtures/productivity.js',import.meta.url),'utf8')});
await page.goto('http://127.0.0.1:4180/?fixture=quick#/quick');
await page.reload();
await page.waitForSelector('loc=css:input[aria-label="빠른 스니펫 검색"]');
